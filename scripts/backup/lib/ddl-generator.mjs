// Generates real, executable DDL for the `public` schema directly from
// live Postgres catalogs (pg_catalog/information_schema), rather than
// from supabase/migrations/. This was verified necessary: the
// migrations directory does NOT contain CREATE TABLE statements for
// several foundational tables (clinics, patients, dentists,
// appointments, clinic_users, profiles) - they predate migration
// tracking in this repo and only ever appear in ALTER TABLE statements.
// Concatenating migrations would therefore produce a backup that fails
// to restore. Catalog introspection reflects whatever is actually
// running in production right now, regardless of migration history.

export function extensionsDDL(extensions) {
  return extensions
    .filter((e) => e.extname !== "plpgsql") // always present in every Postgres database, never needs creating
    .map((e) => `create extension if not exists "${e.extname}";`)
    .join("\n");
}

export async function listCustomEnums(client) {
  const { rows } = await client.query(`
    select t.typname, e.enumlabel, e.enumsortorder
    from pg_type t
    join pg_enum e on t.oid = e.enumtypid
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public'
    order by t.typname, e.enumsortorder
  `);
  const byType = new Map();
  for (const r of rows) {
    if (!byType.has(r.typname)) byType.set(r.typname, []);
    byType.get(r.typname).push(r.enumlabel);
  }
  return [...byType.entries()].map(([name, labels]) => ({ name, labels }));
}

export function enumDDL(enums) {
  return enums
    .map((e) => {
      const labels = e.labels.map((l) => `'${l.replace(/'/g, "''")}'`).join(", ");
      return `do $$ begin\n  create type public."${e.name}" as enum (${labels});\nexception when duplicate_object then null;\nend $$;`;
    })
    .join("\n\n");
}

export async function tableColumns(client, table) {
  const { rows } = await client.query(
    `
    select a.attname as column_name,
           pg_catalog.format_type(a.atttypid, a.atttypmod) as formatted_type,
           a.attnotnull as not_null,
           pg_get_expr(ad.adbin, ad.adrelid) as default_expr,
           a.attidentity as identity,
           a.attgenerated as generated
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    left join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
    where n.nspname = 'public' and c.relname = $1
      and a.attnum > 0 and not a.attisdropped
    order by a.attnum
    `,
    [table]
  );
  return rows;
}

function columnDDL(col) {
  const name = `"${col.column_name}"`;
  const type = col.formatted_type;
  let clause = `  ${name} ${type}`;

  if (col.generated === "s") {
    clause += ` generated always as (${col.default_expr}) stored`;
  } else if (col.identity === "a") {
    clause += ` generated always as identity`;
  } else if (col.identity === "d") {
    clause += ` generated by default as identity`;
  } else if (col.default_expr) {
    clause += ` default ${col.default_expr}`;
  }

  if (col.not_null) clause += " not null";
  return clause;
}

export async function tableDDL(client, table) {
  const cols = await tableColumns(client, table);
  const colLines = cols.map(columnDDL).join(",\n");
  return `create table public."${table}" (\n${colLines}\n);`;
}

export async function listSequenceDefaults(client) {
  // Plain serial/bigserial-style defaults (nextval on a sequence) that
  // are NOT identity columns - identity columns auto-create their
  // sequence, these do not.
  const { rows } = await client.query(`
    select a.attname as column_name, c.relname as "table",
           pg_get_expr(ad.adbin, ad.adrelid) as default_expr
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    join pg_attrdef ad on ad.adrelid = a.attrelid and ad.adnum = a.attnum
    where n.nspname = 'public' and a.attidentity = '' and not a.attisdropped
      and pg_get_expr(ad.adbin, ad.adrelid) like 'nextval(%'
  `);
  return rows;
}

export async function listConstraintsOrdered(client) {
  const { rows } = await client.query(`
    select conname, conrelid::regclass::text as "table", contype,
           pg_get_constraintdef(oid) as definition
    from pg_constraint
    where connamespace = 'public'::regnamespace
    order by case contype when 'p' then 1 when 'u' then 2 when 'c' then 3 when 'f' then 4 else 5 end, conname
  `);
  return rows;
}

export async function listNonConstraintIndexes(client) {
  const { rows } = await client.query(`
    select i.indexname, i.tablename, i.indexdef
    from pg_indexes i
    where i.schemaname = 'public'
      and not exists (
        select 1 from pg_constraint c
        where c.connamespace = 'public'::regnamespace
          and c.conname = i.indexname
      )
    order by i.indexname
  `);
  return rows;
}

export async function listTriggers(client) {
  const { rows } = await client.query(`
    select t.tgname, c.relname as "table", pg_get_triggerdef(t.oid) as definition
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and not t.tgisinternal
    order by t.tgname
  `);
  return rows;
}

export async function listTableGrants(client) {
  const { rows } = await client.query(`
    select table_name, grantee, privilege_type
    from information_schema.role_table_grants
    where table_schema = 'public'
      and grantee in ('anon', 'authenticated', 'service_role')
    order by table_name, grantee, privilege_type
  `);
  return rows;
}

export function grantsDDL(grants) {
  const byTableGrantee = new Map();
  for (const g of grants) {
    const key = `${g.table_name}::${g.grantee}`;
    if (!byTableGrantee.has(key)) byTableGrantee.set(key, []);
    byTableGrantee.get(key).push(g.privilege_type);
  }
  const lines = [];
  for (const [key, privs] of byTableGrantee) {
    const [table, grantee] = key.split("::");
    lines.push(`grant ${privs.join(", ")} on public."${table}" to ${grantee};`);
  }
  return lines.join("\n");
}

// pg_policies.roles is a Postgres `name[]`, which node-postgres does not
// auto-parse into a JS array (no default OID type-parser for `name[]`),
// so it arrives as the raw array literal text e.g. "{public}" or
// "{authenticated,service_role}". Role names never contain commas,
// braces, or quotes, so a plain split is safe here.
function parsePgRoleArray(value) {
  if (Array.isArray(value)) return value;
  if (typeof value === "string" && value.startsWith("{") && value.endsWith("}")) {
    const inner = value.slice(1, -1);
    return inner.length === 0 ? [] : inner.split(",");
  }
  return [value];
}

export function policyDDL(policy) {
  const roles = parsePgRoleArray(policy.roles).join(", ");
  const permissive = policy.permissive === "PERMISSIVE" ? "" : " as restrictive";
  let sql = `create policy "${policy.policyname}" on public."${policy.tablename}"${permissive} for ${policy.cmd.toLowerCase()} to ${roles}`;
  if (policy.qual) sql += ` using (${policy.qual})`;
  if (policy.with_check) sql += ` with check (${policy.with_check})`;
  return sql + ";";
}
